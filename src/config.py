"""
アプリ全体で共有する設定・定数をまとめるモジュール。

【最重要】データリーク防止について
====================================
このアプリは「ジョブを投入する前」に成功確率を予測するためのものである。
そのため、モデルに入力してよい特徴量は「ジョブ投入時点（実行開始前）で
値が確定している情報」に限定しなければならない。

F-DATA (Zenodo DOI: 10.5281/zenodo.11467483) の生カラムのうち、
実行後にしか値が分からない指標（消費電力・実測flops・CPU時間・
実行時間・アイドル時間など）を特徴量に混ぜると、モデルは「答えを
見てから答えを予測する」状態になり、見かけ上の精度は上がるが
実運用（投入前予測）では全く役に立たない。これを防ぐため、
以下で「使ってよい特徴量」と「使ってはいけない特徴量」を明示的に
分離して管理する。
"""

from pathlib import Path

# ------------------------------------------------------------------
# パス関連
# ------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data"
RAW_DIR = DATA_DIR / "raw"  # ダウンロードしたparquet置き場（サイズが大きいためgit管理対象外）
MODELS_DIR = PROJECT_ROOT / "src" / "models"
DOCS_DIR = PROJECT_ROOT / "docs"

MODEL_PATH = MODELS_DIR / "model.pt"
PREPROCESSOR_PATH = MODELS_DIR / "preprocessor.joblib"
CALIBRATOR_PATH = MODELS_DIR / "calibrator.joblib"
METRICS_PATH = MODELS_DIR / "metrics.json"

# Zenodo上のF-DATAレコードID
ZENODO_RECORD_ID = "11467483"
ZENODO_FILES_BASE_URL = f"https://zenodo.org/api/records/{ZENODO_RECORD_ID}/files"

# ------------------------------------------------------------------
# 学習・検証・テストに使う月次parquetファイル
# ------------------------------------------------------------------
# F-DATAは2021年3月〜2024年4月の38ファイル（約28GB）で構成される。
# 本プロジェクトではこのうち2021年3月を除く37ファイルすべてを使う。
#
# 2021年3月（Fugaku運用開始直後の月）は除外している。日別のジョブ投入件数を
# 確認すると、3月7日=1件、3月6日・8日は1000件未満、3月23日以降も1桁〜数百件
# の閑散日が10日ほど続くなど、試験運用・保守期間とみられる極端な変動を
# 含んでおり（4月以降は最も少ない日でも703件と安定している）、通常の利用実態
# を表さないと判断した。
#
# 複数年にわたる期間を学習に使うことで、年による水準の変化や曜日パターンが
# 多くの週にわたって平均化され、狭い期間だけを見た場合に生じがちな
# 「その時期特有のノイズ」を実際の傾向と誤認するリスクを抑えている。
#
# 分割方針（時系列を厳密に守り、trainより未来のデータでval/testを行う）:
#   train: 2021-04 〜 2023-12（33ヶ月）
#   val  : 2024-01, 2024-02（trainより完全に未来）
#   test : 2024-03, 2024-04（データセット最後の2ヶ月、valよりさらに未来）
def _month_range(year_month_pairs):
    return [f"{y:02d}_{m:02d}.parquet" for (y, m) in year_month_pairs]


TRAIN_FILES = (
    _month_range([(21, m) for m in range(4, 13)])  # 2021-04 〜 2021-12
    + _month_range([(22, m) for m in range(1, 13)])  # 2022-01 〜 2022-12
    + _month_range([(23, m) for m in range(1, 13)])  # 2023-01 〜 2023-12
)
VAL_FILES = ["24_01.parquet", "24_02.parquet"]
TEST_FILES = ["24_03.parquet", "24_04.parquet"]

RANDOM_SEED = 42

# ------------------------------------------------------------------
# ターゲット変数
# ------------------------------------------------------------------
# "exit state" カラムは "completed" / "failed" の2値。
# 本アプリでは success = 1 (completed), failure = 0 (failed) として二値分類する。
TARGET_COLUMN = "exit state"
POSITIVE_LABEL = "completed"

# ------------------------------------------------------------------
# 特徴量の切り分け（★データリーク防止の核心部分★）
# ------------------------------------------------------------------

# [OK] 投入時点（ジョブ実行開始より前）に確定している生カラム
#   - nnumr    : ユーザーが要求したノード数
#   - elpl     : ユーザーが指定した経過時間上限（実行時間の"上限"であり実測値ではない）
#   - mszl     : ユーザーが指定したメモリ使用量の上限（実測値ではない）
#   - freq_req : ユーザーが要求した動作周波数
#   - adt      : 投入（到着）日時。ここから曜日・時間帯を特徴量化する
SAFE_RAW_COLUMNS = [
    "nnumr",
    "elpl",
    "mszl",
    "freq_req",
    "adt",
]

# mszl（要求メモリ上限）は、上限を指定しなかったジョブでは
# センチネル値（2^64-1、float64では約1.84e19）が入っている。
# この閾値より大きい値は「上限なし（デフォルト）」とみなす。
MSZL_SENTINEL_THRESHOLD = 1e18

# [NG] 実行後（ジョブ終了後）にしか値が確定しない生カラム。
# 学習・推論のどちらにおいても絶対に特徴量として使ってはならない。
#   - cnumat/cnumut, nnuma/nnumu : 実際に割り当て/使用されたコア数・ノード数
#   - qdt/schedsdt/deldt/sdt/edt : スケジューリング・実行に関する各種タイムスタンプ（adt以外）
#   - idle_time_ave              : 実行中のアイドル時間（実測）
#   - perf1〜perf6                : 実行サイクル数・演算数などのハードウェアカウンタ（実測）
#   - econ/avgpcon/minpcon/maxpcon: 消費電力（実測）
#   - msza/mmszu                 : 実際に割り当て/使用されたメモリ量
#   - uctmut/sctmut/usctmut      : 実測CPU時間
#   - freq_alloc                 : 実際に割り当てられた動作周波数
#   - flops/mbwidth/opint        : 実測flops・メモリ帯域・演算強度
#   - pclass                     : 実行特性から事後的に分類された性能クラス
#   - duration                   : 実際の実行時間（実測）
#   - ec                         : ジョブ終了コード（ターゲットそのもの）
LEAKED_COLUMNS = [
    "cnumat", "cnumut", "nnuma", "nnumu",
    "qdt", "schedsdt", "deldt", "sdt", "edt",
    "idle_time_ave",
    "perf1", "perf2", "perf3", "perf4", "perf5", "perf6",
    "econ", "avgpcon", "minpcon", "maxpcon",
    "msza", "mmszu",
    "uctmut", "sctmut", "usctmut",
    "freq_alloc",
    "flops", "mbwidth", "opint",
    "pclass",
    "duration",
    "ec",
]

# [投入時点で分かるが不使用・安全] 実データを確認した結果、ほぼ定数か
# 重複情報のため特徴量から除外した生カラム（リークではない）。
#   - cnumr : nnumr とほぼ完全に比例（1ノード=48コア固定、標準偏差0）で情報量が重複
#   - pri   : 5種類の値（127, 255, 250, 110, 100）が観測されるが、これが
#             「ユーザーが投入時に指定する値」なのか「スケジューラが
#             qdt〜schedsdt の間に動的に割り当てる値」なのかがデータセットの
#             ドキュメントだけでは判別できない。後者であれば投入前にユーザーが
#             知り得ない値になる（＝リークになり得る）ため、安全側に倒して除外
DROPPED_LOW_SIGNAL_COLUMNS = ["cnumr", "pri"]

# [投入時点で分かるが不使用・時間的に不安定] jobenv_req（ジョブ実行環境、
# キュー／リソースグループに相当、匿名化済み）は、2021年4月〜2024年3月の
# 約3年間はほぼ100%が同一のカテゴリ（jobenv_req_0）で占められているのに
# 対し、2024年4月だけ突然99.9%が別カテゴリ（jobenv_req_1）に切り替わって
# いる。周期的な季節変動ではなく、運用体制か資源配分の枠組みが一度きり
# 変わったことを示す変数だと考えられる。学習データにはほぼ登場しない
# カテゴリがテスト期間の大部分を占めることになるため、この特徴量を使うと
# 未来の期間に全く汎化しない（この変数を含めて学習するとROC-AUCが0.44と
# ランダムより悪化することを確認済み）。リークではなく、時間的に不安定で
# 汎化しないという理由で除外している。
EXCLUDED_UNSTABLE_COLUMNS = ["jobenv_req"]

# [除外] embedding列はジョブ名/ジョブ環境等の機微情報をSentence-BERTで
# 埋め込んだベクトル(384次元)だが、生成元や生成タイミングがデータセット側の
# ドキュメントで明確にされていない。本プロトタイプでは「投入前情報である
# ことが確実な特徴量のみ」を使う方針のため、安全側に倒して特徴量から除外する。
# また jnam（ジョブ名）自体も本来は投入時点で分かる情報だが、そのままでは
# 自由記述文字列でありUIから人間が入力するには不向きなため特徴量に含めない。
# jid（ジョブID）は単なる識別子で予測に有用な情報を含まない。
EXCLUDED_AMBIGUOUS_COLUMNS = ["embedding", "jnam", "jid"]

# usr（投入ユーザーの匿名化ID）は使わない。F-DATAの匿名化IDは実際の冨岳の
# ユーザー名とは対応しておらず、実際の利用者が本アプリに自分のIDを入力しても
# 何の恩恵も受けられない（実運用上意味を持たない特徴量になってしまう）ため、
# 特徴量にもUI入力にも含めていない。詳細は docs/feature_leakage.md を参照。
EXCLUDED_UNUSABLE_COLUMNS = ["usr"]

# ------------------------------------------------------------------
# 最終的にモデルへ入力する特徴量（生カラム + 派生特徴量）
# ------------------------------------------------------------------
NUMERIC_FEATURES = [
    "nnumr_log",          # 要求ノード数（log1p変換、裾の重い分布のため）
    "elpl_hours",         # 要求経過時間上限（時間単位）
    "node_hours_log",     # 要求ノード数×要求時間（log1p変換、総リソース量の目安）
    "mszl_specified",     # メモリ上限を明示的に指定したか（0/1）
    "mszl_gib_log",       # 指定した場合のメモリ上限（GiB, log1p変換。未指定時は0）
    "submit_hour",        # 投入時刻（0-23時）
    "submit_dow",         # 投入曜日（0=月, 6=日）
]
CATEGORICAL_FEATURES = [
    "freq_req",    # 要求周波数（離散値: 2000 / 2200 MHzなど）
]

ALL_FEATURES = NUMERIC_FEATURES + CATEGORICAL_FEATURES

